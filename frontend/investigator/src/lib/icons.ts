/** A record key that is another name for a vocabulary id: the inventory merged each pair as one
 *  attribute in one role (ip with ip_address, event_id with event_ids). Only keys a shipped story
 *  carries are listed. */
export const FIELD_KEY_ALIAS: ReadonlyMap<string, string> = new Map([
  ["ip", "ip_address"],
  ["event_id", "event_ids"],
]);

const KIND_ICON: ReadonlyMap<string, string> = new Map(VOCABULARY.filter((e) => e.kind).map((e) => [e.id, e.icon]));
const FIELD_ICON: ReadonlyMap<string, string> = new Map(VOCABULARY.filter((e) => !e.kind).map((e) => [e.id, e.icon]));

// shortcut: an override can name only an icon of this set (no loader by name); a story that wants
// another icon needs it added here.
function inSet(name: unknown): name is string {
  return typeof name === "string" && Object.hasOwn(ICONS, name);
}

/** The icon of a kind: the story's own (its node's `icon` key) when it names an icon of the set, then the
 *  vocabulary's, then the fallback. */
export function kindIconName(kind: string, nodes: readonly ScenarioNode[]): string {
  const node = nodes.find((n) => n.kind === kind);
  const own = node && Object.hasOwn(node, "icon") ? (node as ScenarioNode & { icon?: unknown }).icon : undefined;
  if (inSet(own)) return own;
  return KIND_ICON.get(kind) ?? FALLBACK_ICON;
}

/** The icon of an attribute, by the field id a row is given (a vocabulary id, or a record's key): the
 *  story's own (the `icon` key of the field's entry in the manifest's root `fields`) when it names an icon
 *  of the set, then the vocabulary's by the id or its alias, then the fallback. */
export function fieldIconName(field: string, fields: Readonly<Record<string, ScenarioFieldWords>> | undefined): string {
  const words: unknown = fields && Object.hasOwn(fields, field) ? fields[field] : undefined;
  const own = typeof words === "object" && words !== null ? (words as { icon?: unknown }).icon : undefined;
  if (inSet(own)) return own;
  return FIELD_ICON.get(FIELD_KEY_ALIAS.get(field) ?? field) ?? FALLBACK_ICON;
}
